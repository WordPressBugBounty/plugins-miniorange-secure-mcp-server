<?php
/**
 * Turns raw HTTP responses into pass/warn/fail check rows.
 *
 * @package Miniorange_Secure_MCP_Server
 */

namespace MoSMCP\Common\Services\Diagnostics;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Class Response_Classifier
 *
 * Pure (no WordPress calls) so every verdict is unit-testable from a mocked response.
 * A response is `array{status:int, headers:array<string,string>, body:string, error:string}`
 * with lowercase header names; status 0 plus a non-empty `error` means a transport failure.
 * Every verdict is `array{status:string, code:string, detail:string}`.
 */
class Response_Classifier {

	const PASS = 'pass';
	const WARN = 'warn';
	const FAIL = 'fail';
	const SKIP = 'skipped';

	/**
	 * Bytes of body inspected when fingerprinting, so a huge page can't slow the check.
	 */
	const BODY_SCAN_LIMIT = 65536;

	/**
	 * Builds a normalized response.
	 *
	 * @param int                  $status  HTTP status, 0 on transport failure.
	 * @param array<string,string> $headers Headers (any case).
	 * @param string               $body    Response body.
	 * @param string               $error   Transport error message, if any.
	 * @return array{status:int, headers:array<string,string>, body:string, error:string}
	 */
	public static function response( $status, array $headers = array(), $body = '', $error = '' ) {
		return array(
			'status'  => (int) $status,
			'headers' => array_change_key_case( array_map( 'strval', $headers ), CASE_LOWER ),
			'body'    => (string) $body,
			'error'   => (string) $error,
		);
	}

	/**
	 * Names what produced a response body.
	 *
	 * @param array $res Normalized response.
	 * @return string json|rest_restricted|cloudflare_challenge|cloudflare_block|wordfence_block|sucuri_block|modsecurity_block|imunify_block|html|empty|unknown
	 */
	public static function fingerprint( array $res ) {
		$headers = $res['headers'];

		if ( isset( $headers['cf-mitigated'] ) && 'challenge' === strtolower( $headers['cf-mitigated'] ) ) {
			return 'cloudflare_challenge';
		}

		$body = substr( $res['body'], 0, self::BODY_SCAN_LIMIT );
		if ( '' === trim( $body ) ) {
			return 'empty';
		}

		$json = json_decode( $body, true );
		if ( is_array( $json ) ) {
			$wp_codes = array( 'rest_forbidden', 'rest_cannot_access', 'rest_not_logged_in', 'rest_login_required' );
			return ( isset( $json['code'] ) && in_array( $json['code'], $wp_codes, true ) ) ? 'rest_restricted' : 'json';
		}

		$lower = strtolower( $body );
		$known = array(
			'cloudflare_challenge' => array( 'just a moment...', 'cf-chl-', '_cf_chl_opt', 'challenge-platform', 'checking your browser before accessing' ),
			'cloudflare_block'     => array( 'attention required! | cloudflare', 'sorry, you have been blocked', 'error code: 1020', 'cloudflare ray id' ),
			'wordfence_block'      => array( 'your access to this site has been limited', 'generated by wordfence' ),
			'sucuri_block'         => array( 'sucuri website firewall', 'access denied - sucuri' ),
			'modsecurity_block'    => array( 'mod_security', 'modsecurity', 'not acceptable!' ),
			'imunify_block'        => array( 'imunify360' ),
		);

		foreach ( $known as $name => $needles ) {
			foreach ( $needles as $needle ) {
				if ( false !== strpos( $lower, $needle ) ) {
					return $name;
				}
			}
		}

		$head = ltrim( substr( $lower, 0, 200 ) );
		if ( 0 === strpos( $head, '<!doctype html' ) || 0 === strpos( $head, '<html' ) || false !== strpos( $head, '<head' ) ) {
			$server = isset( $headers['server'] ) ? strtolower( $headers['server'] ) : '';
			return ( 403 === $res['status'] && 'cloudflare' === $server ) ? 'cloudflare_block' : 'html';
		}

		return 'unknown';
	}

	/**
	 * Maps a transport error message to a short code.
	 *
	 * @param string $message The error message.
	 * @return string dns|tls|refused|timeout|unknown
	 */
	public static function transport_error_code( $message ) {
		$message = strtolower( (string) $message );

		if ( false !== strpos( $message, 'could not resolve host' ) || false !== strpos( $message, 'name or service not known' ) || false !== strpos( $message, 'getaddrinfo' ) ) {
			return 'dns';
		}
		if ( false !== strpos( $message, 'ssl' ) || false !== strpos( $message, 'certificate' ) ) {
			return 'tls';
		}
		if ( false !== strpos( $message, 'connection refused' ) ) {
			return 'refused';
		}
		if ( false !== strpos( $message, 'timed out' ) || false !== strpos( $message, 'timeout' ) ) {
			return 'timeout';
		}

		return 'unknown';
	}

	/**
	 * Whether response headers show the body came from a cache layer.
	 *
	 * @param array<string,string> $headers Lowercase headers.
	 * @return bool
	 */
	public static function served_from_cache( array $headers ) {
		$cache_headers = array( 'x-litespeed-cache', 'x-cache', 'x-proxy-cache', 'x-fastcgi-cache', 'x-cache-status', 'cf-cache-status' );

		foreach ( $cache_headers as $name ) {
			if ( isset( $headers[ $name ] ) && preg_match( '/\b(hit|stale|revalidated|updating)\b/i', $headers[ $name ] ) ) {
				return true;
			}
		}

		return isset( $headers['age'] ) && (int) $headers['age'] > 0;
	}

	/**
	 * Classifies the failure modes shared by every endpoint: transport errors, firewall pages,
	 * rate limiting, server errors and redirects.
	 *
	 * @param array $res Normalized response.
	 * @return array|null A fail verdict, or null when the response got through to a real answer.
	 */
	public static function common_failure( array $res ) {
		if ( '' !== $res['error'] ) {
			return self::transport_failure( $res['error'] );
		}

		$status = $res['status'];
		$print  = self::fingerprint( $res );

		$blocks = array(
			'cloudflare_challenge' => __( 'Cloudflare is showing its "Just a moment" challenge to automated requests, so AI clients cannot get through.', 'miniorange-secure-mcp-server' ),
			'cloudflare_block'     => __( 'Cloudflare blocked the request (firewall or bot rule).', 'miniorange-secure-mcp-server' ),
			'wordfence_block'      => __( 'Wordfence blocked the request.', 'miniorange-secure-mcp-server' ),
			'sucuri_block'         => __( 'The Sucuri firewall blocked the request.', 'miniorange-secure-mcp-server' ),
			'modsecurity_block'    => __( 'ModSecurity (a server firewall) blocked the request.', 'miniorange-secure-mcp-server' ),
			'imunify_block'        => __( 'Imunify360 (a server firewall) blocked the request.', 'miniorange-secure-mcp-server' ),
		);
		if ( isset( $blocks[ $print ] ) ) {
			return self::verdict( self::FAIL, $print, $blocks[ $print ] );
		}

		if ( 'rest_restricted' === $print ) {
			return self::verdict( self::FAIL, 'rest_restricted', __( 'WordPress or a security plugin is restricting the REST API to logged-in users.', 'miniorange-secure-mcp-server' ) );
		}

		if ( 403 === $status || 406 === $status ) {
			if ( 'html' === $print ) {
				return self::verdict( self::FAIL, 'waf_block', __( 'A firewall or host security layer returned a 403 block page.', 'miniorange-secure-mcp-server' ) );
			}
			return self::verdict( self::FAIL, 'blocked_403', __( 'The request was refused with a 403 Forbidden.', 'miniorange-secure-mcp-server' ) );
		}

		if ( 429 === $status ) {
			return self::verdict( self::FAIL, 'rate_limited', __( 'The request was rate limited (429) by the host or a firewall.', 'miniorange-secure-mcp-server' ) );
		}

		if ( $status >= 500 ) {
			/* translators: %d: HTTP status code. */
			return self::verdict( self::FAIL, 'server_error', sprintf( __( 'The site returned a server error (%d).', 'miniorange-secure-mcp-server' ), $status ) );
		}

		if ( $status >= 300 && $status < 400 ) {
			$location = isset( $res['headers']['location'] ) ? self::strip_query( $res['headers']['location'] ) : '';
			/* translators: 1: HTTP status code, 2: redirect target. */
			$detail = sprintf( __( 'The request was redirected (%1$d) to %2$s. AI clients do not follow redirects safely, so the redirect must be removed.', 'miniorange-secure-mcp-server' ), $status, '' !== $location ? $location : __( 'another URL', 'miniorange-secure-mcp-server' ) );
			return self::verdict( self::FAIL, 'redirect', $detail );
		}

		return null;
	}

	/**
	 * Classifies the plugin's /health document.
	 *
	 * @param array $res Normalized response.
	 * @return array
	 */
	public static function classify_health( array $res ) {
		$fail = self::common_failure( $res );
		if ( null !== $fail ) {
			return $fail;
		}

		$json = ( 200 === $res['status'] ) ? json_decode( $res['body'], true ) : null;
		if ( 200 === $res['status'] && is_array( $json ) && isset( $json['service'] ) && 'mosmcp' === $json['service'] ) {
			return self::verdict( self::PASS, 'ok', __( 'The plugin answered.', 'miniorange-secure-mcp-server' ) );
		}

		return self::unexpected( $res, 200 );
	}

	/**
	 * Classifies an OAuth discovery document: 200 JSON, no redirect, not a stale cached copy.
	 *
	 * @param array  $res             Normalized response.
	 * @param string $expected_origin Scheme+host the document should advertise, '' to skip the staleness test.
	 * @return array
	 */
	public static function classify_wellknown( array $res, $expected_origin = '' ) {
		$fail = self::common_failure( $res );
		if ( null !== $fail ) {
			return $fail;
		}

		$cached = self::served_from_cache( $res['headers'] );
		$type   = isset( $res['headers']['content-type'] ) ? strtolower( $res['headers']['content-type'] ) : '';
		$json   = json_decode( $res['body'], true );

		if ( 200 !== $res['status'] ) {
			return self::unexpected( $res, 200 );
		}

		if ( false === strpos( $type, 'json' ) || ! is_array( $json ) ) {
			if ( $cached ) {
				return self::verdict( self::FAIL, 'cached_response', __( 'A page cache is serving a stored web page at this address instead of the live OAuth document.', 'miniorange-secure-mcp-server' ) );
			}
			return self::verdict( self::FAIL, 'html_response', __( 'The address returned a web page instead of JSON, so something is intercepting it.', 'miniorange-secure-mcp-server' ) );
		}

		if ( $cached ) {
			$advertised = isset( $json['issuer'] ) ? $json['issuer'] : ( isset( $json['resource'] ) ? $json['resource'] : '' );
			if ( '' !== $expected_origin && is_string( $advertised ) && '' !== $advertised && self::origin( $advertised ) !== self::origin( $expected_origin ) ) {
				return self::verdict( self::FAIL, 'stale_cached_doc', __( 'A cache is serving an out-of-date copy of this document that advertises a different address.', 'miniorange-secure-mcp-server' ) );
			}
			return self::verdict( self::WARN, 'cached_response', __( 'The document is served from a cache. It works today, but a cached copy goes stale if the site address changes.', 'miniorange-secure-mcp-server' ) );
		}

		return self::verdict( self::PASS, 'ok', __( 'Valid JSON, no redirect, not cached.', 'miniorange-secure-mcp-server' ) );
	}

	/**
	 * Classifies the unauthenticated MCP request into three dependent rows.
	 *
	 * @param array $res Normalized response to a POST carrying a dummy bearer token.
	 * @return array{mcp:array, www_authenticate:array, auth_header:array}
	 */
	public static function classify_mcp_endpoint( array $res ) {
		$skip = function ( $reason ) {
			return self::verdict( self::SKIP, 'not_reached', $reason );
		};

		$fail = self::common_failure( $res );
		if ( null !== $fail ) {
			$why = __( 'Skipped: the MCP endpoint could not be reached.', 'miniorange-secure-mcp-server' );
			return array(
				'mcp'              => $fail,
				'www_authenticate' => $skip( $why ),
				'auth_header'      => $skip( $why ),
			);
		}

		$status  = $res['status'];
		$headers = $res['headers'];
		$json    = json_decode( $res['body'], true );
		$shaped  = is_array( $json ) && ( isset( $json['error'] ) || isset( $json['jsonrpc'] ) );
		$why     = __( 'Skipped: the request did not reach the plugin.', 'miniorange-secure-mcp-server' );

		if ( 401 === $status && isset( $headers['www-authenticate'] ) && 0 === stripos( ltrim( $headers['www-authenticate'] ), 'basic' ) ) {
			return array(
				'mcp'              => self::verdict( self::FAIL, 'basic_auth', __( 'The site is behind HTTP Basic authentication (a password prompt), which blocks AI clients before WordPress runs.', 'miniorange-secure-mcp-server' ) ),
				'www_authenticate' => $skip( $why ),
				'auth_header'      => $skip( $why ),
			);
		}

		if ( 401 !== $status || ! $shaped ) {
			$print = self::fingerprint( $res );
			$mcp   = ( 200 === $status && 'html' === $print )
				? self::verdict( self::FAIL, 'html_response', __( 'The MCP address returned a web page instead of the plugin, so a cache or redirect rule is intercepting it.', 'miniorange-secure-mcp-server' ) )
				: self::unexpected( $res, 401 );

			return array(
				'mcp'              => $mcp,
				'www_authenticate' => $skip( $why ),
				'auth_header'      => $skip( $why ),
			);
		}

		$mcp = self::verdict( self::PASS, 'ok', __( 'The endpoint answered 401 as expected.', 'miniorange-secure-mcp-server' ) );

		$www = ( isset( $headers['www-authenticate'] ) && '' !== trim( $headers['www-authenticate'] ) )
			? self::verdict( self::PASS, 'ok', __( 'The 401 carries a WWW-Authenticate header.', 'miniorange-secure-mcp-server' ) )
			: self::verdict( self::FAIL, 'missing_challenge_header', __( 'The 401 has no WWW-Authenticate header, so AI clients cannot discover how to sign in. A proxy or firewall is stripping it.', 'miniorange-secure-mcp-server' ) );

		return array(
			'mcp'              => $mcp,
			'www_authenticate' => $www,
			'auth_header'      => self::classify_auth_header( $res ),
		);
	}

	/**
	 * Reads the plugin's header-echo flag to tell "token rejected" from "header never arrived".
	 *
	 * @param array $res Normalized response from the MCP endpoint.
	 * @return array
	 */
	public static function classify_auth_header( array $res ) {
		$seen = isset( $res['headers']['x-mosmcp-auth-header-seen'] ) ? $res['headers']['x-mosmcp-auth-header-seen'] : null;

		if ( '1' === $seen ) {
			return self::verdict( self::PASS, 'ok', __( 'The Authorization header reaches WordPress.', 'miniorange-secure-mcp-server' ) );
		}
		if ( '0' === $seen ) {
			return self::verdict( self::FAIL, 'auth_header_stripped', __( 'The server removed the Authorization header before WordPress saw it, so every AI request looks signed out.', 'miniorange-secure-mcp-server' ) );
		}

		return self::verdict( self::WARN, 'auth_header_unknown', __( 'The plugin did not report whether the Authorization header arrived (a proxy may be stripping response headers).', 'miniorange-secure-mcp-server' ) );
	}

	/**
	 * Classifies a deliberately invalid OAuth registration/token call: a clean 4xx JSON error is healthy.
	 *
	 * @param array $res Normalized response.
	 * @return array
	 */
	public static function classify_oauth_error( array $res ) {
		$fail = self::common_failure( $res );
		if ( null !== $fail ) {
			return $fail;
		}

		$json = json_decode( $res['body'], true );
		if ( $res['status'] >= 400 && $res['status'] < 500 && is_array( $json ) && isset( $json['error'] ) ) {
			return self::verdict( self::PASS, 'ok', __( 'The endpoint rejected the test request with a clean OAuth error, as it should.', 'miniorange-secure-mcp-server' ) );
		}

		return self::unexpected( $res, 400 );
	}

	/**
	 * Classifies the anonymous authorization-endpoint call: a 400 or a redirect is healthy.
	 *
	 * @param array $res Normalized response (redirects not followed).
	 * @return array
	 */
	public static function classify_authorize( array $res ) {
		if ( '' === $res['error'] && $res['status'] >= 300 && $res['status'] < 400 ) {
			return self::verdict( self::PASS, 'ok', __( 'The authorization endpoint responded.', 'miniorange-secure-mcp-server' ) );
		}

		$fail = self::common_failure( $res );
		if ( null !== $fail ) {
			return $fail;
		}

		if ( 400 === $res['status'] ) {
			return self::verdict( self::PASS, 'ok', __( 'The authorization endpoint responded.', 'miniorange-secure-mcp-server' ) );
		}

		return self::unexpected( $res, 400 );
	}

	/**
	 * Builds a verdict row.
	 *
	 * @param string $status pass|warn|fail|skipped.
	 * @param string $code   Machine code the fix catalog keys on.
	 * @param string $detail Plain-language explanation.
	 * @return array{status:string, code:string, detail:string}
	 */
	public static function verdict( $status, $code, $detail ) {
		return array(
			'status' => $status,
			'code'   => $code,
			'detail' => $detail,
		);
	}

	/**
	 * Verdict for a response that got through but is not what the check expects.
	 *
	 * @param array $res      Normalized response.
	 * @param int   $expected The status the check expected.
	 * @return array
	 */
	private static function unexpected( array $res, $expected ) {
		/* translators: 1: expected HTTP status, 2: actual HTTP status. */
		return self::verdict( self::FAIL, 'unexpected_response', sprintf( __( 'Expected a %1$d response from the plugin but got %2$d with an unexpected body.', 'miniorange-secure-mcp-server' ), $expected, $res['status'] ) );
	}

	/**
	 * Verdict for a transport-level failure.
	 *
	 * @param string $message The transport error message.
	 * @return array
	 */
	private static function transport_failure( $message ) {
		$kind    = self::transport_error_code( $message );
		$details = array(
			'dns'     => __( 'The address could not be resolved (DNS).', 'miniorange-secure-mcp-server' ),
			'tls'     => __( 'The HTTPS certificate was rejected (expired, mismatched or incomplete chain).', 'miniorange-secure-mcp-server' ),
			'refused' => __( 'The connection was refused.', 'miniorange-secure-mcp-server' ),
			'timeout' => __( 'The request timed out.', 'miniorange-secure-mcp-server' ),
			'unknown' => __( 'The request failed before any response arrived.', 'miniorange-secure-mcp-server' ),
		);

		return self::verdict( self::FAIL, 'transport_' . $kind, $details[ $kind ] );
	}

	/**
	 * Drops the query string from a URL so redirect targets never echo parameters into a report.
	 *
	 * @param string $url The URL.
	 * @return string
	 */
	private static function strip_query( $url ) {
		$pos = strpos( $url, '?' );

		return false === $pos ? $url : substr( $url, 0, $pos );
	}

	/**
	 * Lowercased scheme://host of a URL.
	 *
	 * @param string $url The URL.
	 * @return string
	 */
	private static function origin( $url ) {
		$parts = parse_url( $url ); // phpcs:ignore WordPress.WP.AlternativeFunctions.parse_url_parse_url -- WP-free by design.

		return is_array( $parts ) && isset( $parts['host'] )
			? strtolower( ( isset( $parts['scheme'] ) ? $parts['scheme'] : '' ) . '://' . $parts['host'] )
			: '';
	}
}
